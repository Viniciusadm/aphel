use clap::{Args, ValueEnum};

use crate::cli::CliResult;
use crate::cli::modules::short_type;
use aphel_kernel::modules::unified_catalog::{self, CatalogDocument, HookEntry};

const HOST_HOOKS_INTRO: &str = include_str!("catalog/host_hooks.md");
const HOST_OPERATIONS_INTRO: &str = include_str!("catalog/host_operations.md");
const KERNEL_MODULE: &str = "kernel";

#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
pub(crate) enum MarkdownDocument {
    Hooks,
    Host,
}

#[derive(Debug, Clone, PartialEq, Eq, Args)]
pub(crate) struct CatalogArgs {
    #[arg(long, help = "Print the whole catalog as JSON")]
    pub(crate) json: bool,
    #[arg(
        long,
        value_enum,
        help = "Print a generated document: hooks (docs/modules/hooks.md) or host (docs/plugins/host-catalog.md)"
    )]
    pub(crate) markdown: Option<MarkdownDocument>,
}

pub(crate) fn run(args: CatalogArgs) -> CliResult {
    let document = unified_catalog::build(aphel_kernel::modules::app());
    if args.json {
        println!("{}", serde_json::to_string_pretty(&document)?);
        return Ok(());
    }
    match args.markdown {
        Some(MarkdownDocument::Hooks) => print!("{}", hooks_markdown(&document)),
        Some(MarkdownDocument::Host) => print!("{}", host_markdown(&document)),
        None => summary(&document),
    }
    Ok(())
}

fn summary(document: &CatalogDocument) {
    println!("Aphel {}", document.version);
    println!("\nPLUGINS");
    for plugin in &document.plugins {
        println!(
            "  {:<22} {:<11} {:<7} provides: {}",
            plugin.key,
            plugin.layer.unwrap_or("-"),
            plugin.runtime,
            if plugin.provides.is_empty() {
                "-".to_owned()
            } else {
                plugin.provides.join(", ")
            }
        );
    }
    println!("\nOPERATIONS ({})", document.operations.len());
    for operation in &document.operations {
        println!(
            "  {:<32} {:<9} {}",
            operation.key, operation.effect, operation.module
        );
    }
    println!("\nHOOKS ({})", document.hooks.len());
    for hook in &document.hooks {
        println!("  {:<44} {:<24} {}", hook.key, hook.kind, hook.module);
    }
    println!("\nEVENTS ({})", document.events.len());
    println!("PERMISSIONS ({})", document.permissions.len());
    println!(
        "NOTIFICATION KINDS ({})",
        document
            .extensions
            .get("notification_kinds")
            .and_then(serde_json::Value::as_array)
            .map_or(0, Vec::len)
    );
}

fn cell(value: &str) -> String {
    value.replace('|', "\\|")
}

fn hook_path(name: &str) -> String {
    name.strip_prefix("aphel_mod_").unwrap_or(name).to_owned()
}

fn hooks_markdown(document: &CatalogDocument) -> String {
    let mut declared: Vec<&HookEntry> = document
        .hooks
        .iter()
        .filter(|hook| hook.args.is_some())
        .collect();
    declared.sort_by_key(|hook| (hook.module != KERNEL_MODULE, hook.module));
    let mut output = String::from("# Hook catalog\n\n");
    output.push_str("Generated by `aphel catalog --markdown hooks` from the plugins in this build. Do not edit by hand: run `cargo run -q -p aphel -- catalog --markdown hooks > ../docs/modules/hooks.md` in `back/` (or `make catalog-docs`).\n\n");
    output.push_str("Usage: `veto` and `action` are registered with `app.on(Hook, priority, handler)` (an error from a `veto` cancels the operation); `filter` with `app.filter(Hook, priority, handler)`, which returns the changed value. Lower priority runs first.\n\n");
    output.push_str("| Hook | Module | Usage | Argument | When | Listeners |\n");
    output.push_str("| --- | --- | --- | --- | --- | --- |\n");
    for hook in declared {
        let listeners = if hook.listeners.is_empty() {
            "-".to_owned()
        } else {
            hook.listeners.join(", ")
        };
        output.push_str(&format!(
            "| `{}` | `{}` | {} | `{}` | {} | {} |\n",
            hook_path(&hook.key),
            hook.module,
            hook.kind,
            short_type(hook.args.as_deref().unwrap_or_default()),
            cell(&hook.description),
            listeners
        ));
    }
    output
}

fn host_markdown(document: &CatalogDocument) -> String {
    let mut output = String::from(HOST_HOOKS_INTRO);
    output.push_str("| Hook | Module | Record type | Kind | Values |\n");
    output.push_str("| --- | --- | --- | --- | --- |\n");
    let mut hooks: Vec<&HookEntry> = document
        .hooks
        .iter()
        .filter(|hook| hook.record_type.is_some())
        .collect();
    hooks.sort_by_key(|hook| (hook.module != "plugins", hook.key.clone()));
    for hook in hooks {
        let record_type = match hook.record_type.as_deref() {
            Some("any") | Some("*") | None => "any".to_owned(),
            Some(value) => format!("`{value}`"),
        };
        output.push_str(&format!(
            "| `{}` | {} | {} | {} | {} |\n",
            hook.key,
            hook.module,
            record_type,
            hook.kind,
            cell(&hook.description)
        ));
    }
    output.push('\n');
    output.push_str(HOST_OPERATIONS_INTRO);
    output.push_str("| Operation | Module | Access | Durable | Input and result |\n");
    output.push_str("| --- | --- | --- | --- | --- |\n");
    for operation in &document.operations {
        output.push_str(&format!(
            "| `{}` | {} | {} | {} | {} |\n",
            operation.key,
            operation.module,
            if operation.effect == "read" {
                "read"
            } else {
                "write"
            },
            if operation.durable {
                "yes"
            } else if operation.effect == "read" {
                "—"
            } else {
                "no"
            },
            cell(operation.description)
        ));
    }
    output
}
