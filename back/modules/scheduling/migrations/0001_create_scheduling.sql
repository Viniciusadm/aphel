CREATE TABLE scheduling_availability (
  user_id CHAR(36) NOT NULL,
  timezone VARCHAR(64) NOT NULL,
  weekly_hours JSON NOT NULL,
  min_notice_minutes INT NOT NULL DEFAULT 240,
  max_per_day INT NULL,
  buffer_before_minutes INT NOT NULL DEFAULT 0,
  buffer_after_minutes INT NOT NULL DEFAULT 0,
  horizon_days INT NOT NULL DEFAULT 60,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (user_id),
  CONSTRAINT scheduling_availability_user_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE meeting_types (
  id CHAR(36) NOT NULL,
  owner_id CHAR(36) NOT NULL,
  slug VARCHAR(80) NOT NULL,
  name VARCHAR(140) NOT NULL,
  description TEXT NULL,
  duration_minutes INT NOT NULL,
  slot_interval_minutes INT NOT NULL DEFAULT 30,
  location_kind VARCHAR(16) NOT NULL DEFAULT 'none',
  location_value VARCHAR(500) NULL,
  questions JSON NOT NULL,
  spam_protection BOOLEAN NOT NULL DEFAULT TRUE,
  distribution_rule_id CHAR(36) NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY meeting_types_slug_unique (slug),
  KEY meeting_types_owner_fk_index (owner_id),
  KEY meeting_types_rule_fk_index (distribution_rule_id),
  CONSTRAINT meeting_types_owner_fk FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT meeting_types_rule_fk FOREIGN KEY (distribution_rule_id) REFERENCES lead_distribution_rules (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE meeting_bookings (
  id CHAR(36) NOT NULL,
  meeting_type_id CHAR(36) NOT NULL,
  host_user_id CHAR(36) NOT NULL,
  contact_id CHAR(36) NULL,
  activity_id CHAR(36) NULL,
  status VARCHAR(16) NOT NULL,
  starts_at DATETIME(6) NOT NULL,
  ends_at DATETIME(6) NOT NULL,
  guest_name VARCHAR(200) NOT NULL,
  guest_email VARCHAR(320) NOT NULL,
  guest_timezone VARCHAR(64) NULL,
  guest_locale VARCHAR(10) NULL,
  answers JSON NOT NULL,
  revision INT NOT NULL DEFAULT 0,
  cancel_reason VARCHAR(500) NULL,
  canceled_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY meeting_bookings_host_index (host_user_id, status, starts_at),
  KEY meeting_bookings_type_index (meeting_type_id, starts_at),
  KEY meeting_bookings_contact_index (contact_id),
  CONSTRAINT meeting_bookings_type_fk FOREIGN KEY (meeting_type_id) REFERENCES meeting_types (id) ON DELETE CASCADE,
  CONSTRAINT meeting_bookings_host_fk FOREIGN KEY (host_user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
