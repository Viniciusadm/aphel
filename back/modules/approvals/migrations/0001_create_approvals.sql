CREATE TABLE approval_policies (
  id CHAR(36) NOT NULL,
  `key` VARCHAR(80) NOT NULL,
  name VARCHAR(140) NOT NULL,
  description TEXT NULL,
  record_type VARCHAR(64) NOT NULL,
  moment VARCHAR(20) NOT NULL,
  target_id CHAR(36) NULL,
  condition_kind VARCHAR(10) NOT NULL DEFAULT 'always',
  condition_filter JSON NULL,
  condition_formula TEXT NULL,
  locked_fields JSON NOT NULL,
  due_hours INT UNSIGNED NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  position INT NOT NULL DEFAULT 0,
  created_by CHAR(36) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY approval_policies_key_unique (`key`),
  KEY approval_policies_lookup_index (record_type, moment, is_active),
  KEY approval_policies_created_by_fk_index (created_by),
  CONSTRAINT approval_policies_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE approval_policy_steps (
  id CHAR(36) NOT NULL,
  policy_id CHAR(36) NOT NULL,
  position INT UNSIGNED NOT NULL,
  name VARCHAR(140) NULL,
  approver_kind VARCHAR(24) NOT NULL,
  approver_user_id CHAR(36) NULL,
  approver_role_id CHAR(36) NULL,
  rule VARCHAR(8) NOT NULL DEFAULT 'any',
  PRIMARY KEY (id),
  UNIQUE KEY approval_policy_steps_position_unique (policy_id, position),
  KEY approval_policy_steps_user_fk_index (approver_user_id),
  KEY approval_policy_steps_role_fk_index (approver_role_id),
  CONSTRAINT approval_policy_steps_policy_fk FOREIGN KEY (policy_id) REFERENCES approval_policies (id) ON DELETE CASCADE,
  CONSTRAINT approval_policy_steps_user_fk FOREIGN KEY (approver_user_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT approval_policy_steps_role_fk FOREIGN KEY (approver_role_id) REFERENCES roles (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE approval_requests (
  id CHAR(36) NOT NULL,
  policy_id CHAR(36) NULL,
  policy_name VARCHAR(140) NOT NULL,
  record_type VARCHAR(64) NOT NULL,
  record_id CHAR(36) NOT NULL,
  moment VARCHAR(20) NOT NULL,
  target_id CHAR(36) NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'pending',
  current_step INT UNSIGNED NOT NULL DEFAULT 0,
  steps JSON NOT NULL,
  locked_fields JSON NOT NULL,
  comment TEXT NULL,
  requested_by CHAR(36) NULL,
  requested_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  due_at DATETIME(6) NULL,
  resolved_at DATETIME(6) NULL,
  resolved_by CHAR(36) NULL,
  resolution_comment TEXT NULL,
  consumed_at DATETIME(6) NULL,
  overdue_notified_at DATETIME(6) NULL,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  target_marker CHAR(36) GENERATED ALWAYS AS (COALESCE(target_id, '')) STORED,
  is_open TINYINT(1) GENERATED ALWAYS AS (CASE WHEN status = 'pending' THEN 1 END) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY approval_requests_open_unique (policy_id, record_type, record_id, moment, target_marker, is_open),
  KEY approval_requests_record_index (record_type, record_id, status),
  KEY approval_requests_requested_by_index (requested_by, status),
  KEY approval_requests_resolved_by_fk_index (resolved_by),
  KEY approval_requests_overdue_index (status, due_at, overdue_notified_at),
  CONSTRAINT approval_requests_policy_fk FOREIGN KEY (policy_id) REFERENCES approval_policies (id) ON DELETE SET NULL,
  CONSTRAINT approval_requests_requested_by_fk FOREIGN KEY (requested_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT approval_requests_resolved_by_fk FOREIGN KEY (resolved_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE approval_request_approvers (
  request_id CHAR(36) NOT NULL,
  step_position INT UNSIGNED NOT NULL,
  user_id CHAR(36) NOT NULL,
  decision VARCHAR(10) NULL,
  comment TEXT NULL,
  decided_at DATETIME(6) NULL,
  PRIMARY KEY (request_id, step_position, user_id),
  KEY approval_request_approvers_inbox_index (user_id, decision),
  CONSTRAINT approval_request_approvers_request_fk FOREIGN KEY (request_id) REFERENCES approval_requests (id) ON DELETE CASCADE,
  CONSTRAINT approval_request_approvers_user_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
