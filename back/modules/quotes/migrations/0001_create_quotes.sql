CREATE TABLE quotes (
  id CHAR(36) NOT NULL,
  deal_id CHAR(36) NOT NULL,
  number INT UNSIGNED NOT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  is_current BOOLEAN NOT NULL DEFAULT TRUE,
  title VARCHAR(255) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'draft',
  owner_id CHAR(36) NULL,
  contact_id CHAR(36) NULL,
  company_id CHAR(36) NULL,
  currency CHAR(3) NOT NULL,
  price_list_id CHAR(36) NULL,
  valid_until DATE NULL,
  terms TEXT NULL,
  notes TEXT NULL,
  discount_type VARCHAR(16) NOT NULL DEFAULT 'none',
  discount_value DECIMAL(18,2) NOT NULL DEFAULT 0,
  subtotal DECIMAL(18,2) NOT NULL DEFAULT 0,
  discount_total DECIMAL(18,2) NOT NULL DEFAULT 0,
  tax_total DECIMAL(18,2) NOT NULL DEFAULT 0,
  total DECIMAL(18,2) NOT NULL DEFAULT 0,
  exceeds_discount_limit BOOLEAN NOT NULL DEFAULT FALSE,
  public_key CHAR(32) NULL,
  sent_at DATETIME(6) NULL,
  sent_by CHAR(36) NULL,
  viewed_at DATETIME(6) NULL,
  accepted_at DATETIME(6) NULL,
  accepted_name VARCHAR(160) NULL,
  accepted_email VARCHAR(255) NULL,
  accepted_ip VARCHAR(64) NULL,
  accepted_user_agent VARCHAR(512) NULL,
  rejected_at DATETIME(6) NULL,
  rejection_reason TEXT NULL,
  expired_at DATETIME(6) NULL,
  deal_synced_at DATETIME(6) NULL,
  deal_sync_error VARCHAR(500) NULL,
  created_by CHAR(36) NULL,
  deleted_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  current_number INT UNSIGNED GENERATED ALWAYS AS (IF(is_current AND deleted_at IS NULL, number, NULL)) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY quotes_number_version_unique (number, version),
  UNIQUE KEY quotes_current_unique (current_number),
  UNIQUE KEY quotes_public_key_unique (public_key),
  KEY quotes_deal_index (deal_id, number),
  KEY quotes_status_index (status, valid_until),
  KEY quotes_created_index (created_at),
  KEY quotes_owner_fk_index (owner_id),
  KEY quotes_contact_fk_index (contact_id),
  KEY quotes_company_fk_index (company_id),
  KEY quotes_sent_by_fk_index (sent_by),
  KEY quotes_created_by_fk_index (created_by),
  CONSTRAINT quotes_owner_fk FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT quotes_sent_by_fk FOREIGN KEY (sent_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT quotes_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE quote_items (
  id CHAR(36) NOT NULL,
  quote_id CHAR(36) NOT NULL,
  position INT NOT NULL DEFAULT 0,
  product_id CHAR(36) NULL,
  name VARCHAR(255) NOT NULL,
  description TEXT NULL,
  unit VARCHAR(32) NULL,
  quantity DECIMAL(18,4) NOT NULL,
  unit_price DECIMAL(18,2) NOT NULL,
  discount_type VARCHAR(16) NOT NULL DEFAULT 'none',
  discount_value DECIMAL(18,2) NOT NULL DEFAULT 0,
  tax_percent DECIMAL(9,4) NOT NULL DEFAULT 0,
  recurrence VARCHAR(16) NOT NULL DEFAULT 'none',
  term_months SMALLINT UNSIGNED NULL,
  components JSON NOT NULL DEFAULT (JSON_ARRAY()),
  gross DECIMAL(18,2) NOT NULL DEFAULT 0,
  discount_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
  total_discount_share DECIMAL(18,2) NOT NULL DEFAULT 0,
  tax_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
  total DECIMAL(18,2) NOT NULL DEFAULT 0,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY quote_items_quote_index (quote_id, position),
  KEY quote_items_product_fk_index (product_id),
  CONSTRAINT quote_items_quote_fk FOREIGN KEY (quote_id) REFERENCES quotes (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE quote_counters (
  id TINYINT UNSIGNED NOT NULL,
  last_number INT UNSIGNED NOT NULL DEFAULT 0,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT quote_counters_single_row CHECK (id = 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE quote_settings (
  id TINYINT UNSIGNED NOT NULL,
  default_valid_days SMALLINT UNSIGNED NULL,
  default_terms TEXT NULL,
  accept_stages JSON NOT NULL DEFAULT (JSON_OBJECT()),
  updated_by CHAR(36) NULL,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT quote_settings_single_row CHECK (id = 1),
  KEY quote_settings_updated_by_fk_index (updated_by),
  CONSTRAINT quote_settings_updated_by_fk FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

