CREATE TABLE sequences (
  id CHAR(36) NOT NULL,
  `key` VARCHAR(64) NOT NULL,
  name VARCHAR(200) NOT NULL,
  description VARCHAR(1000) NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  window_start_minute SMALLINT UNSIGNED NOT NULL DEFAULT 480,
  window_end_minute SMALLINT UNSIGNED NOT NULL DEFAULT 1080,
  daily_limit INT UNSIGNED NOT NULL DEFAULT 50,
  created_by CHAR(36) NULL,
  updated_by CHAR(36) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY sequences_key_unique (`key`),
  KEY sequences_name_index (name),
  KEY sequences_created_by_fk_index (created_by),
  KEY sequences_updated_by_fk_index (updated_by),
  CONSTRAINT sequences_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT sequences_updated_by_fk FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE sequence_steps (
  id CHAR(36) NOT NULL,
  sequence_id CHAR(36) NOT NULL,
  position INT UNSIGNED NOT NULL,
  kind VARCHAR(16) NOT NULL,
  wait_days INT UNSIGNED NOT NULL DEFAULT 0,
  template_id CHAR(36) NULL,
  subject VARCHAR(1000) NOT NULL DEFAULT '',
  body_html MEDIUMTEXT NULL,
  title VARCHAR(200) NOT NULL DEFAULT '',
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY sequence_steps_position_unique (sequence_id, position),
  KEY sequence_steps_template_fk_index (template_id),
  CONSTRAINT sequence_steps_sequence_fk FOREIGN KEY (sequence_id) REFERENCES sequences (id) ON DELETE CASCADE,
  CONSTRAINT sequence_steps_template_fk FOREIGN KEY (template_id) REFERENCES email_templates (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE sequence_enrollments (
  id CHAR(36) NOT NULL,
  sequence_id CHAR(36) NOT NULL,
  contact_id CHAR(36) NOT NULL,
  enrolled_by CHAR(36) NOT NULL,
  mailbox_id CHAR(36) NULL,
  source VARCHAR(16) NOT NULL,
  status VARCHAR(16) NOT NULL,
  current_position INT UNSIGNED NOT NULL DEFAULT 0,
  next_run_at DATETIME(6) NULL,
  last_email_id CHAR(36) NULL,
  exit_reason VARCHAR(32) NULL,
  exit_position INT UNSIGNED NULL,
  paused_at DATETIME(6) NULL,
  completed_at DATETIME(6) NULL,
  exited_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  is_live TINYINT(1) GENERATED ALWAYS AS (CASE WHEN status IN ('active', 'paused') THEN 1 END) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY sequence_enrollments_live_unique (sequence_id, contact_id, is_live),
  KEY sequence_enrollments_due_index (status, next_run_at),
  KEY sequence_enrollments_sequence_index (sequence_id, status),
  KEY sequence_enrollments_contact_index (contact_id, status),
  KEY sequence_enrollments_enrolled_by_fk_index (enrolled_by),
  KEY sequence_enrollments_mailbox_fk_index (mailbox_id),
  CONSTRAINT sequence_enrollments_sequence_fk FOREIGN KEY (sequence_id) REFERENCES sequences (id) ON DELETE CASCADE,
  CONSTRAINT sequence_enrollments_contact_fk FOREIGN KEY (contact_id) REFERENCES contacts (id) ON DELETE CASCADE,
  CONSTRAINT sequence_enrollments_enrolled_by_fk FOREIGN KEY (enrolled_by) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT sequence_enrollments_mailbox_fk FOREIGN KEY (mailbox_id) REFERENCES mailboxes (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE sequence_step_runs (
  id CHAR(36) NOT NULL,
  sequence_id CHAR(36) NOT NULL,
  enrollment_id CHAR(36) NOT NULL,
  step_id CHAR(36) NULL,
  position INT UNSIGNED NOT NULL,
  kind VARCHAR(16) NOT NULL,
  status VARCHAR(16) NOT NULL,
  contact_id CHAR(36) NOT NULL,
  mailbox_id CHAR(36) NULL,
  email_id CHAR(36) NULL,
  thread_id CHAR(36) NULL,
  activity_id CHAR(36) NULL,
  failure_reason VARCHAR(500) NULL,
  executed_at DATETIME(6) NOT NULL,
  opened_at DATETIME(6) NULL,
  replied_at DATETIME(6) NULL,
  bounced_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY sequence_step_runs_position_unique (enrollment_id, position),
  KEY sequence_step_runs_metrics_index (sequence_id, position),
  KEY sequence_step_runs_contact_index (contact_id, kind, executed_at),
  KEY sequence_step_runs_mailbox_index (mailbox_id, kind, executed_at),
  KEY sequence_step_runs_email_index (email_id),
  KEY sequence_step_runs_thread_index (thread_id),
  KEY sequence_step_runs_step_fk_index (step_id),
  CONSTRAINT sequence_step_runs_sequence_fk FOREIGN KEY (sequence_id) REFERENCES sequences (id) ON DELETE CASCADE,
  CONSTRAINT sequence_step_runs_enrollment_fk FOREIGN KEY (enrollment_id) REFERENCES sequence_enrollments (id) ON DELETE CASCADE,
  CONSTRAINT sequence_step_runs_step_fk FOREIGN KEY (step_id) REFERENCES sequence_steps (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
