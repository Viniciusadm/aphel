CREATE TABLE products (
  id CHAR(36) NOT NULL,
  name VARCHAR(255) NOT NULL,
  code VARCHAR(64) NULL,
  active_code VARCHAR(64) GENERATED ALWAYS AS (IF(deleted_at IS NULL, code, NULL)) STORED,
  description TEXT NULL,
  price DECIMAL(18,2) NOT NULL DEFAULT 0,
  currency CHAR(3) NOT NULL,
  unit VARCHAR(32) NULL,
  recurrence VARCHAR(16) NOT NULL DEFAULT 'none',
  term_months SMALLINT UNSIGNED NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_by CHAR(36) NULL,
  deleted_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY products_code_unique (active_code),
  KEY products_name_index (name),
  KEY products_active_index (is_active),
  KEY products_created_index (created_at),
  KEY products_created_by_fk_index (created_by),
  CONSTRAINT products_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
