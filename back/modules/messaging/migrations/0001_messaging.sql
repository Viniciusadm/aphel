CREATE TABLE messaging_channels (
  id CHAR(36) NOT NULL,
  kind VARCHAR(16) NOT NULL,
  name VARCHAR(120) NOT NULL,
  config JSON NOT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  last_error VARCHAR(500) NULL,
  last_checked_at DATETIME(6) NULL,
  last_polled_at DATETIME(6) NULL,
  imap_uid_validity BIGINT UNSIGNED NULL,
  imap_last_uid BIGINT UNSIGNED NULL,
  acting_user_id CHAR(36) NULL,
  created_by CHAR(36) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY messaging_channels_kind_index (kind, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE messaging_conversations (
  id CHAR(36) NOT NULL,
  channel_id CHAR(36) NOT NULL,
  peer VARCHAR(320) NOT NULL,
  peer_name VARCHAR(255) NULL,
  subject VARCHAR(500) NULL,
  contact_id CHAR(36) NULL,
  deal_id CHAR(36) NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'open',
  assignee_user_id CHAR(36) NULL,
  unread_count INT UNSIGNED NOT NULL DEFAULT 0,
  last_message_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  last_inbound_at DATETIME(6) NULL,
  last_message_preview VARCHAR(255) NULL,
  last_message_direction VARCHAR(8) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY messaging_conversations_inbox_index (status, last_message_at),
  KEY messaging_conversations_assignee_index (assignee_user_id, last_message_at),
  KEY messaging_conversations_contact_index (contact_id),
  KEY messaging_conversations_deal_index (deal_id),
  KEY messaging_conversations_peer_index (channel_id, peer),
  CONSTRAINT messaging_conversations_channel_fk FOREIGN KEY (channel_id) REFERENCES messaging_channels (id) ON DELETE CASCADE,
  CONSTRAINT messaging_conversations_assignee_fk FOREIGN KEY (assignee_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE messaging_messages (
  id CHAR(36) NOT NULL,
  conversation_id CHAR(36) NOT NULL,
  channel_id CHAR(36) NOT NULL,
  direction VARCHAR(8) NOT NULL,
  external_id VARCHAR(255) NULL,
  sender VARCHAR(320) NOT NULL,
  sender_name VARCHAR(255) NULL,
  subject VARCHAR(500) NULL,
  body MEDIUMTEXT NOT NULL,
  message_type VARCHAR(32) NOT NULL DEFAULT 'text',
  status VARCHAR(16) NOT NULL,
  error_code VARCHAR(64) NULL,
  error_message VARCHAR(500) NULL,
  in_reply_to VARCHAR(500) NULL,
  thread_references TEXT NULL,
  sent_by_user_id CHAR(36) NULL,
  provider_timestamp DATETIME(6) NULL,
  sent_at DATETIME(6) NULL,
  delivered_at DATETIME(6) NULL,
  read_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY messaging_messages_external_unique (channel_id, external_id),
  KEY messaging_messages_conversation_index (conversation_id, created_at),
  KEY messaging_messages_status_index (status),
  CONSTRAINT messaging_messages_conversation_fk FOREIGN KEY (conversation_id) REFERENCES messaging_conversations (id) ON DELETE CASCADE,
  CONSTRAINT messaging_messages_channel_fk FOREIGN KEY (channel_id) REFERENCES messaging_channels (id) ON DELETE CASCADE,
  CONSTRAINT messaging_messages_sender_fk FOREIGN KEY (sent_by_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
