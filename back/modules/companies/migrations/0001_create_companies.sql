CREATE TABLE companies (
  id CHAR(36) NOT NULL,
  owner_id CHAR(36) NULL,
  name VARCHAR(255) NOT NULL,
  domain VARCHAR(255) NULL,
  website VARCHAR(2048) NULL,
  industry VARCHAR(140) NULL,
  size_range VARCHAR(64) NULL,
  phone VARCHAR(32) NULL,
  email VARCHAR(320) NULL,
  address_street VARCHAR(255) NULL,
  address_number VARCHAR(32) NULL,
  address_complement VARCHAR(140) NULL,
  address_district VARCHAR(140) NULL,
  address_city VARCHAR(140) NULL,
  address_state VARCHAR(140) NULL,
  address_postal_code VARCHAR(32) NULL,
  address_country VARCHAR(2) NULL,
  description TEXT NULL,
  source VARCHAR(140) NULL,
  parent_company_id CHAR(36) NULL,
  created_by CHAR(36) NULL,
  archived_at DATETIME(6) NULL,
  deleted_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  last_contacted_at DATETIME(6) NULL,
  last_email_received_at DATETIME(6) NULL,
  last_email_sent_at DATETIME(6) NULL,
  interaction_count INT NOT NULL DEFAULT 0,
  last_contacted_by CHAR(36) NULL,
  PRIMARY KEY (id),
  KEY companies_name_index (name),
  KEY companies_domain_index (domain),
  KEY companies_created_index (created_at),
  KEY companies_updated_index (updated_at),
  KEY companies_deleted_index (deleted_at),
  KEY companies_owner_fk_index (owner_id),
  KEY companies_parent_fk_index (parent_company_id),
  KEY companies_last_contacted_index (last_contacted_at),
  KEY companies_last_contacted_by_fk_index (last_contacted_by),
  CONSTRAINT companies_owner_fk FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT companies_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT companies_parent_fk FOREIGN KEY (parent_company_id) REFERENCES companies (id) ON DELETE SET NULL,
  CONSTRAINT companies_last_contacted_by_fk FOREIGN KEY (last_contacted_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
