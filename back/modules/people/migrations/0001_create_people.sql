CREATE TABLE people (
  id CHAR(36) NOT NULL,
  owner_id CHAR(36) NULL,
  company_id CHAR(36) NULL,
  first_name VARCHAR(140) NOT NULL,
  last_name VARCHAR(140) NULL,
  full_name VARCHAR(281) GENERATED ALWAYS AS (TRIM(CONCAT_WS(' ', first_name, last_name))) STORED,
  email VARCHAR(320) NULL,
  phone VARCHAR(32) NULL,
  mobile VARCHAR(32) NULL,
  job_title VARCHAR(140) NULL,
  address_street VARCHAR(255) NULL,
  address_number VARCHAR(32) NULL,
  address_complement VARCHAR(140) NULL,
  address_district VARCHAR(140) NULL,
  address_city VARCHAR(140) NULL,
  address_state VARCHAR(140) NULL,
  address_postal_code VARCHAR(32) NULL,
  address_country VARCHAR(2) NULL,
  source VARCHAR(140) NULL,
  notes TEXT NULL,
  created_by CHAR(36) NULL,
  archived_at DATETIME(6) NULL,
  deleted_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  last_contacted_at DATETIME(6) NULL,
  last_email_received_at DATETIME(6) NULL,
  last_email_sent_at DATETIME(6) NULL,
  interaction_count INT NOT NULL DEFAULT 0,
  last_contacted_by CHAR(36) NULL,
  PRIMARY KEY (id),
  KEY people_name_index (full_name),
  KEY people_email_index (email),
  KEY people_phone_index (phone),
  KEY people_mobile_index (mobile),
  KEY people_created_index (created_at),
  KEY people_updated_index (updated_at),
  KEY people_deleted_index (deleted_at),
  KEY people_company_fk_index (company_id),
  KEY people_owner_fk_index (owner_id),
  KEY people_last_contacted_index (last_contacted_at),
  KEY people_last_contacted_by_fk_index (last_contacted_by),
  CONSTRAINT people_owner_fk FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT people_company_fk FOREIGN KEY (company_id) REFERENCES organizations (id) ON DELETE SET NULL,
  CONSTRAINT people_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT people_last_contacted_by_fk FOREIGN KEY (last_contacted_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE people_organizations (
  id CHAR(36) NOT NULL,
  contact_id CHAR(36) NOT NULL,
  company_id CHAR(36) NOT NULL,
  role VARCHAR(64) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY people_organizations_unique (contact_id, company_id),
  KEY people_organizations_company_fk_index (company_id),
  CONSTRAINT people_organizations_contact_fk FOREIGN KEY (contact_id) REFERENCES people (id) ON DELETE CASCADE,
  CONSTRAINT people_organizations_company_fk FOREIGN KEY (company_id) REFERENCES organizations (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
