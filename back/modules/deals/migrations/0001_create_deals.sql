CREATE TABLE deals (
  id CHAR(36) NOT NULL,
  owner_id CHAR(36) NULL,
  pipeline_id CHAR(36) NOT NULL,
  stage_id CHAR(36) NOT NULL,
  title VARCHAR(255) NOT NULL,
  amount DECIMAL(18,2) NULL,
  currency CHAR(3) NOT NULL,
  amount_base DECIMAL(18,2) NULL,
  exchange_rate DECIMAL(24,10) NULL,
  mrr DECIMAL(18,2) NULL,
  arr DECIMAL(18,2) NULL,
  tcv DECIMAL(18,2) NULL,
  contract_start DATE NULL,
  contract_end DATE NULL,
  renewal_of_deal_id CHAR(36) NULL,
  probability TINYINT UNSIGNED NULL,
  expected_close_date DATE NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'open',
  closed_at DATETIME(6) NULL,
  lost_reason_id CHAR(36) NULL,
  lost_reason_note TEXT NULL,
  source VARCHAR(140) NULL,
  contact_id CHAR(36) NULL,
  company_id CHAR(36) NULL,
  stage_entered_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  last_activity_at DATETIME(6) NULL,
  created_by CHAR(36) NULL,
  archived_at DATETIME(6) NULL,
  deleted_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY deals_stage_index (pipeline_id, stage_id, status),
  KEY deals_status_index (status, expected_close_date),
  KEY deals_created_index (created_at),
  KEY deals_title_index (title),
  KEY deals_stage_fk_index (stage_id),
  KEY deals_contact_fk_index (contact_id),
  KEY deals_company_fk_index (company_id),
  KEY deals_owner_fk_index (owner_id),
  KEY deals_lost_reason_fk_index (lost_reason_id),
  KEY deals_deleted_index (deleted_at),
  KEY deals_updated_index (updated_at),
  KEY deals_stage_entered_index (stage_entered_at),
  KEY deals_last_activity_index (last_activity_at),
  KEY deals_expected_close_index (expected_close_date),
  KEY deals_contract_end_index (status, contract_end),
  UNIQUE KEY deals_renewal_of_unique (renewal_of_deal_id),
  KEY deals_currency_index (status, currency),
  CONSTRAINT deals_owner_fk FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT deals_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT deals_renewal_of_fk FOREIGN KEY (renewal_of_deal_id) REFERENCES deals (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE deal_contacts (
  id CHAR(36) NOT NULL,
  deal_id CHAR(36) NOT NULL,
  contact_id CHAR(36) NOT NULL,
  role VARCHAR(64) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY deal_contacts_unique (deal_id, contact_id),
  KEY deal_contacts_contact_fk_index (contact_id),
  CONSTRAINT deal_contacts_deal_fk FOREIGN KEY (deal_id) REFERENCES deals (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE deal_stage_history (
  id CHAR(36) NOT NULL,
  deal_id CHAR(36) NOT NULL,
  stage_id CHAR(36) NOT NULL,
  from_stage_id CHAR(36) NULL,
  entered_at DATETIME(6) NOT NULL,
  event_id CHAR(36) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY deal_stage_history_deal_index (deal_id, entered_at),
  KEY deal_stage_history_stage_index (stage_id, entered_at),
  CONSTRAINT deal_stage_history_deal_fk FOREIGN KEY (deal_id) REFERENCES deals (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE deal_member_roles (
  id CHAR(36) NOT NULL,
  `key` VARCHAR(64) NOT NULL,
  name VARCHAR(140) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  position INT NOT NULL DEFAULT 0,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY deal_member_roles_key_unique (`key`),
  KEY deal_member_roles_position_index (position)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE deal_members (
  id CHAR(36) NOT NULL,
  deal_id CHAR(36) NOT NULL,
  user_id CHAR(36) NOT NULL,
  role_id CHAR(36) NULL,
  credit_percent DECIMAL(5,2) NOT NULL DEFAULT 0,
  added_by CHAR(36) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY deal_members_deal_user_unique (deal_id, user_id),
  KEY deal_members_access_index (user_id, deal_id),
  KEY deal_members_role_fk_index (role_id),
  KEY deal_members_added_by_fk_index (added_by),
  CONSTRAINT deal_members_deal_fk FOREIGN KEY (deal_id) REFERENCES deals (id) ON DELETE CASCADE,
  CONSTRAINT deal_members_user_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT deal_members_role_fk FOREIGN KEY (role_id) REFERENCES deal_member_roles (id) ON DELETE SET NULL,
  CONSTRAINT deal_members_added_by_fk FOREIGN KEY (added_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
