CREATE TABLE task_recurrences (
  id CHAR(36) NOT NULL,
  frequency VARCHAR(16) NOT NULL,
  interval_count INT UNSIGNED NOT NULL DEFAULT 1,
  weekdays VARCHAR(32) NULL,
  month_day TINYINT UNSIGNED NULL,
  until_date DATE NULL,
  max_count INT UNSIGNED NULL,
  anchor_at DATETIME(6) NOT NULL,
  title VARCHAR(255) NOT NULL,
  activity_type_id CHAR(36) NOT NULL,
  owner_id CHAR(36) NULL,
  priority VARCHAR(16) NOT NULL DEFAULT 'normal',
  description TEXT NULL,
  duration_minutes INT UNSIGNED NULL,
  reminder_minutes_before INT UNSIGNED NULL,
  record_type VARCHAR(64) NULL,
  record_id CHAR(36) NULL,
  links JSON NULL,
  ended_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY task_recurrences_ended_at_index (ended_at),
  KEY task_recurrences_type_fk_index (activity_type_id),
  KEY task_recurrences_owner_fk_index (owner_id),
  CONSTRAINT task_recurrences_type_fk FOREIGN KEY (activity_type_id) REFERENCES task_types (id),
  CONSTRAINT task_recurrences_owner_fk FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tasks (
  id CHAR(36) NOT NULL,
  owner_id CHAR(36) NULL,
  created_by CHAR(36) NULL,
  activity_type_id CHAR(36) NOT NULL,
  title VARCHAR(255) NOT NULL,
  description TEXT NULL,
  priority VARCHAR(16) NOT NULL DEFAULT 'normal',
  status VARCHAR(16) NOT NULL DEFAULT 'open',
  due_at DATETIME(6) NULL,
  completed_at DATETIME(6) NULL,
  record_type VARCHAR(64) NULL,
  record_id CHAR(36) NULL,
  duration_minutes INT UNSIGNED NULL,
  location_latitude DECIMAL(9,6) NULL,
  location_longitude DECIMAL(9,6) NULL,
  location_accuracy_m INT UNSIGNED NULL,
  location_captured_at DATETIME(6) NULL,
  recurrence_id CHAR(36) NULL,
  recurrence_index INT UNSIGNED NULL,
  reminder_minutes_before INT UNSIGNED NULL,
  reminder_at DATETIME(6) NULL,
  reminder_sent_at DATETIME(6) NULL,
  deleted_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY activities_recurrence_occurrence_unique (recurrence_id, recurrence_index),
  KEY activities_owner_index (owner_id, status, due_at),
  KEY activities_status_index (status, due_at),
  KEY activities_record_index (record_type, record_id, created_at),
  KEY activities_created_index (created_at),
  KEY activities_updated_index (updated_at),
  KEY activities_reminder_index (status, reminder_sent_at, reminder_at),
  KEY activities_type_fk_index (activity_type_id),
  KEY activities_created_by_fk_index (created_by),
  CONSTRAINT activities_owner_fk FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT activities_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT activities_type_fk FOREIGN KEY (activity_type_id) REFERENCES task_types (id),
  CONSTRAINT activities_recurrence_fk FOREIGN KEY (recurrence_id) REFERENCES task_recurrences (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE task_links (
  id CHAR(36) NOT NULL,
  activity_id CHAR(36) NOT NULL,
  record_type VARCHAR(64) NOT NULL,
  record_id CHAR(36) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY task_links_unique (activity_id, record_type, record_id),
  KEY task_links_record_index (record_type, record_id),
  CONSTRAINT task_links_activity_fk FOREIGN KEY (activity_id) REFERENCES tasks (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
