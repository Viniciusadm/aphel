CREATE TABLE import_jobs (
  id CHAR(36) NOT NULL,
  record_type VARCHAR(64) NOT NULL,
  file_id CHAR(36) NULL,
  file_name VARCHAR(255) NOT NULL,
  status VARCHAR(16) NOT NULL,
  encoding VARCHAR(16) NOT NULL,
  delimiter VARCHAR(4) NOT NULL,
  headers JSON NOT NULL,
  preview JSON NOT NULL,
  row_count INT UNSIGNED NOT NULL,
  mapping JSON NOT NULL,
  options JSON NOT NULL,
  totals JSON NOT NULL,
  error_file_id CHAR(36) NULL,
  retry_of CHAR(36) NULL,
  failure_reason VARCHAR(500) NULL,
  created_by CHAR(36) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  started_at DATETIME(6) NULL,
  finished_at DATETIME(6) NULL,
  privacy_redacted_at DATETIME(6) NULL,
  PRIMARY KEY (id),
  KEY import_jobs_created_at_index (created_at),
  KEY import_jobs_created_by_index (created_by, created_at),
  KEY import_jobs_file_fk_index (file_id),
  KEY import_jobs_error_file_fk_index (error_file_id),
  CONSTRAINT import_jobs_file_fk FOREIGN KEY (file_id) REFERENCES files (id) ON DELETE CASCADE,
  CONSTRAINT import_jobs_error_file_fk FOREIGN KEY (error_file_id) REFERENCES files (id) ON DELETE SET NULL,
  CONSTRAINT import_jobs_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE import_rows (
  import_job_id CHAR(36) NOT NULL,
  row_index INT UNSIGNED NOT NULL,
  status VARCHAR(16) NOT NULL,
  action VARCHAR(16) NULL,
  record_id CHAR(36) NULL,
  errors JSON NULL,
  raw JSON NOT NULL,
  processed_at DATETIME(6) NULL,
  PRIMARY KEY (import_job_id, row_index),
  KEY import_rows_status_index (import_job_id, status, row_index),
  CONSTRAINT import_rows_job_fk FOREIGN KEY (import_job_id) REFERENCES import_jobs (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
