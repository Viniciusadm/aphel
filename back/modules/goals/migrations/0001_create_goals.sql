CREATE TABLE goals (
  id CHAR(36) NOT NULL,
  owner_type VARCHAR(16) NOT NULL,
  user_id CHAR(36) NULL,
  team_id CHAR(36) NULL,
  metric VARCHAR(32) NOT NULL,
  period VARCHAR(16) NOT NULL,
  starts_on DATE NOT NULL,
  ends_on DATE NOT NULL,
  target DECIMAL(18,2) NOT NULL,
  credit_mode VARCHAR(16) NOT NULL DEFAULT 'owner',
  created_by CHAR(36) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY goals_period_index (starts_on, ends_on),
  KEY goals_owner_index (owner_type, metric, period, starts_on),
  KEY goals_user_fk_index (user_id),
  KEY goals_team_fk_index (team_id),
  KEY goals_created_by_fk_index (created_by),
  CONSTRAINT goals_user_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT goals_team_fk FOREIGN KEY (team_id) REFERENCES teams (id) ON DELETE CASCADE,
  CONSTRAINT goals_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
