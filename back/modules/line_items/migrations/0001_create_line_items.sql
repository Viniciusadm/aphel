CREATE TABLE line_items (
  id CHAR(36) NOT NULL,
  record_type VARCHAR(128) NOT NULL,
  record_id CHAR(36) NOT NULL,
  product_id CHAR(36) NULL,
  name VARCHAR(255) NOT NULL,
  unit VARCHAR(32) NULL,
  quantity DECIMAL(18,4) NOT NULL,
  unit_price DECIMAL(18,2) NOT NULL,
  discount_type VARCHAR(16) NOT NULL DEFAULT 'none',
  discount_value DECIMAL(18,2) NOT NULL DEFAULT 0,
  tax_percent DECIMAL(7,4) NOT NULL DEFAULT 0,
  recurrence VARCHAR(16) NOT NULL DEFAULT 'none',
  term_months SMALLINT UNSIGNED NULL,
  total DECIMAL(18,2) NOT NULL,
  amount_base DECIMAL(18,2) NULL,
  exchange_rate DECIMAL(24,10) NULL,
  position INT NOT NULL DEFAULT 0,
  created_by CHAR(36) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY line_items_record_index (record_type, record_id, position),
  KEY line_items_product_fk_index (product_id),
  KEY line_items_created_by_fk_index (created_by),
  CONSTRAINT line_items_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
