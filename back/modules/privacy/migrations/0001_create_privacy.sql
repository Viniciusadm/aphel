CREATE TABLE privacy_requests (
  id CHAR(36) NOT NULL,
  kind VARCHAR(16) NOT NULL,
  status VARCHAR(16) NOT NULL,
  subject_kind VARCHAR(16) NOT NULL,
  subject_label VARCHAR(255) NOT NULL,
  subject_hash CHAR(64) NOT NULL,
  targets JSON NOT NULL,
  due_at DATETIME(6) NOT NULL,
  requested_by CHAR(36) NULL,
  executed_by CHAR(36) NULL,
  result JSON NULL,
  failure_reason VARCHAR(500) NULL,
  file_id CHAR(36) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  started_at DATETIME(6) NULL,
  finished_at DATETIME(6) NULL,
  PRIMARY KEY (id),
  KEY privacy_requests_status_index (status, due_at),
  KEY privacy_requests_created_index (created_at),
  KEY privacy_requests_subject_index (subject_hash),
  KEY privacy_requests_file_fk_index (file_id),
  KEY privacy_requests_requested_by_fk_index (requested_by),
  KEY privacy_requests_executed_by_fk_index (executed_by),
  CONSTRAINT privacy_requests_file_fk FOREIGN KEY (file_id) REFERENCES files (id) ON DELETE SET NULL,
  CONSTRAINT privacy_requests_requested_by_fk FOREIGN KEY (requested_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT privacy_requests_executed_by_fk FOREIGN KEY (executed_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE retention_policies (
  id CHAR(36) NOT NULL,
  name VARCHAR(140) NOT NULL,
  action VARCHAR(32) NOT NULL,
  record_type VARCHAR(64) NULL,
  threshold_days INT UNSIGNED NOT NULL,
  is_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  previewed_count BIGINT UNSIGNED NULL,
  previewed_at DATETIME(6) NULL,
  last_run_at DATETIME(6) NULL,
  created_by CHAR(36) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY retention_policies_created_at_index (created_at),
  KEY retention_policies_enabled_index (is_enabled),
  KEY retention_policies_created_by_fk_index (created_by),
  CONSTRAINT retention_policies_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE retention_runs (
  id CHAR(36) NOT NULL,
  policy_id CHAR(36) NULL,
  policy_name VARCHAR(140) NOT NULL,
  action VARCHAR(32) NOT NULL,
  record_type VARCHAR(64) NULL,
  threshold_days INT UNSIGNED NOT NULL,
  trigger_kind VARCHAR(16) NOT NULL,
  status VARCHAR(16) NOT NULL,
  affected BIGINT UNSIGNED NOT NULL DEFAULT 0,
  files_removed BIGINT UNSIGNED NOT NULL DEFAULT 0,
  errors INT UNSIGNED NOT NULL DEFAULT 0,
  error_message VARCHAR(500) NULL,
  requested_by CHAR(36) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  started_at DATETIME(6) NULL,
  finished_at DATETIME(6) NULL,
  PRIMARY KEY (id),
  KEY retention_runs_created_at_index (created_at),
  KEY retention_runs_policy_index (policy_id, created_at),
  KEY retention_runs_requested_by_fk_index (requested_by),
  CONSTRAINT retention_runs_policy_fk FOREIGN KEY (policy_id) REFERENCES retention_policies (id) ON DELETE SET NULL,
  CONSTRAINT retention_runs_requested_by_fk FOREIGN KEY (requested_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
